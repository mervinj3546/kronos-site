"""Generate the site's color tokens from a seed.

Run with no arguments to roll a new seed, or pass --seed N to rebuild a
palette you liked. The script rewrites the block between the PALETTE markers
in styles.css and records the seed there, so the page always says which seed
made it.

Colors are picked in OKLCH, so lightness steps look even across hues. Every
palette is checked for WCAG contrast before it is written.
"""

import argparse
import math
import random
import re
import secrets
from pathlib import Path

CSS = Path(__file__).with_name("styles.css")
START, END = "/* PALETTE:start", "/* PALETTE:end */"


def oklch_to_srgb(l, c, h):
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (l - 0.0894841775 * a - 1.2914855480 * b) ** 3
    lin = (
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_,
    )
    return tuple(12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055 for x in lin)


def to_rgb(l, c, h):
    """OKLCH to 8-bit sRGB, lowering chroma until the color is in gamut."""
    while True:
        rgb = oklch_to_srgb(l, c, h)
        if all(-0.0005 <= x <= 1.0005 for x in rgb) or c <= 0:
            return tuple(round(min(max(x, 0), 1) * 255) for x in rgb)
        c -= 0.002


def luminance(rgb):
    lin = [x / 255 for x in rgb]
    lin = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in lin]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def build(seed):
    rnd = random.Random(seed)
    hue = rnd.uniform(0, 360)                  # neutrals lean toward this hue
    tint = rnd.uniform(0.006, 0.028)           # how strongly they lean
    accent_h = (hue + rnd.choice([0, 30, 150, 180, 210])) % 360
    accent_c = rnd.uniform(0.11, 0.19)
    accent_l = rnd.uniform(0.72, 0.82)
    alt_h = (accent_h + rnd.uniform(100, 160) * rnd.choice([-1, 1])) % 360

    t = {
        "bg": to_rgb(0.145, tint, hue),
        "panel": to_rgb(0.185, tint, hue),
        "panel-2": to_rgb(0.165, tint, hue),
        "border": to_rgb(0.28, tint * 1.2, hue),
        "border-subtle": to_rgb(0.22, tint, hue),
        "dot": to_rgb(0.32, tint, hue),
        "text": to_rgb(0.96, tint * 0.4, hue),
        "text-2": to_rgb(0.74, tint * 0.8, hue),
        "text-3": to_rgb(0.64, tint * 0.8, hue),
        "accent": to_rgb(accent_l, accent_c, accent_h),
        "accent-bright": to_rgb(min(accent_l + 0.07, 0.92), accent_c * 0.9, accent_h),
        "on-accent": to_rgb(0.18, accent_c * 0.35, accent_h),
        "alt": to_rgb(0.78, accent_c * 0.8, alt_h),
        "pos": to_rgb(0.78, 0.15, 150),
        "neg": to_rgb(0.70, 0.16, 25),
    }
    checks = {
        "text on bg": (contrast(t["text"], t["bg"]), 7),
        "text-2 on panel": (contrast(t["text-2"], t["panel"]), 4.5),
        "text-3 on bg": (contrast(t["text-3"], t["bg"]), 4.5),
        "accent on bg": (contrast(t["accent"], t["bg"]), 4.5),
        "on-accent on accent": (contrast(t["on-accent"], t["accent"]), 4.5),
    }
    params = f"hue {hue:.0f}, tint {tint:.3f}, accent {accent_h:.0f}/{accent_c:.3f}/{accent_l:.2f}, alt {alt_h:.0f}"
    return t, checks, params


def css_block(seed, tokens, params):
    hexes = "\n".join(f"  --{k}: #{''.join(f'{x:02X}' for x in v)};" for k, v in tokens.items())
    rgbs = "\n".join(f"  --{k}-rgb: {' '.join(map(str, tokens[k]))};" for k in ("bg", "accent", "alt"))
    return f"{START} seed {seed} ({params}). Generated by palette.py; do not edit by hand. */\n{hexes}\n{rgbs}\n  {END}"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", type=int, help="rebuild the palette for this seed")
    args = parser.parse_args()

    seed = args.seed
    while True:
        if seed is None:
            candidate = secrets.randbelow(2 ** 32)
        else:
            candidate = seed
        tokens, checks, params = build(candidate)
        failed = [f"{name} {ratio:.2f} < {need}" for name, (ratio, need) in checks.items() if ratio < need]
        if not failed:
            break
        if seed is not None:
            raise SystemExit(f"seed {seed} fails contrast: {'; '.join(failed)}")

    text = CSS.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit("PALETTE markers not found in styles.css")
    CSS.write_text(pattern.sub(lambda _: css_block(candidate, tokens, params), text, count=1))
    print(f"seed {candidate}: {params}")
    for name, (ratio, need) in checks.items():
        print(f"  {name}: {ratio:.2f} (min {need})")


if __name__ == "__main__":
    main()
